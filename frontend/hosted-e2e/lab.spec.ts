import { test, expect } from "@playwright/test";
import { auditAccessibility } from "../test-support/accessibility";

test("paired-computer guidance, suite comparisons and bounded discovery use the private relay", async ({ page, request }, testInfo) => {
  const errors: string[] = [], destinations: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", current => destinations.push(new URL(current.url()).origin));
  async function control(action: string) {
    const result = await request.post(`http://127.0.0.1:8059/${action}`, { headers: { Authorization: `Bearer ${process.env.POLTERGEIST_HOSTED_FIXTURE_TOKEN}` }, data: { name: "lab" } });
    expect(result.status()).toBe(200); return result.json();
  }
  await page.goto("/app/");
  await page.getByRole("button", { name: "New here? Create an account" }).click();
  await page.getByLabel("Username", { exact: true }).fill("guidedtester");
  await page.getByLabel("Password", { exact: true }).fill("private browser fixture passphrase");
  await page.getByRole("button", { name: "Create account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your lab, connected." })).toBeVisible();
  const created = await control("new");
  await page.getByLabel("Pairing code", { exact: true }).fill(created.code);
  await page.getByRole("button", { name: "Connect computer", exact: true }).click();
  await expect(page.getByText("Waiting for local approval", { exact: true })).toBeVisible();
  await control("approve");
  await expect(page.getByRole("button", { name: "Run experiment", exact: true })).toBeEnabled();
  await page.getByRole("navigation", { name: "Workspace" }).getByRole("link", { name: "Guided lab", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Your experiment lab" })).toBeVisible();
  await page.getByRole("button", { name: "Choose Sudden Braking", exact: true }).click();
  expect((await control("state")).runs).toBe(0);
  await page.getByRole("button", { name: "Run one synthetic experiment", exact: true }).click();
  await expect(page.getByRole("heading", { name: "3. Explain what was recorded" })).toBeVisible();
  expect((await control("state")).runs).toBe(1);
  const analyst = page.getByRole("region", { name: "Evidence Analyst", exact: true });
  await analyst.getByRole("button", { name: "Analyze recorded evidence", exact: true }).click();
  await expect(analyst.getByRole("button", { name: "Download evidence analysis" })).toBeVisible();
  await expect(analyst).toContainText("Synthetic mode");
  expect((await control("state")).runs).toBe(1);
  const highlight = page.getByRole("region", { name: "Replay highlights" }).getByRole("link", { name: /^Inspect frame / }).first();
  await expect(highlight).toBeVisible(); await highlight.click();
  await expect(page.getByRole("region", { name: "Selected recorded frame" })).toBeVisible();
  await expect(page.getByRole("region", { name: "Selected recorded frame" })).toContainText("Contacts");
  await expect(page.getByRole("region", { name: "Selected recorded frame" }).getByText("Reading the exact recorded frame…")).not.toBeVisible();
  await auditAccessibility(page, testInfo, "hosted-guided-frame");
  await page.getByRole("link", { name: "Return to guided lab" }).click();
  await page.getByRole("button", { name: "Keep scenes for a comparison" }).click();
  await page.getByLabel("Suite name", { exact: true }).fill("Paired computer suite");
  // A previous evidence read can still hold the computer's one transfer slot
  // after navigating away. Exercise that refusal deterministically.
  const saves: string[] = [];
  await page.route("**/v1/devices/*/experimentation", async route => {
    if (route.request().postDataJSON()?.action?.kind !== "suite_save") { await route.continue(); return; }
    saves.push(route.request().postData()!);
    if (saves.length === 1) await route.fulfill({ status: 429, headers: { "Retry-After": "1" }, json: { error: { code: "transfer_busy" } } });
    else await route.continue();
  });
  await page.getByRole("button", { name: "Save experiment suite", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Paired computer suite", exact: true })).toBeVisible();
  expect(saves.length).toBeGreaterThanOrEqual(2);
  expect(new Set(saves).size).toBe(1);
  await page.getByRole("button", { name: "Run Paired computer suite · 1 executions", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Suite run · completed", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Comparison for Sudden Braking" })).toContainText("1 / 1");
  expect((await control("state")).runs).toBe(2);
  const regression = page.getByRole("region", { name: "Regression Agent", exact: true });
  await regression.getByRole("button", { name: "Review version regression", exact: true }).click();
  await expect(regression.getByRole("heading", { name: "Inconclusive", exact: true })).toBeVisible();
  await expect(regression).toContainText("Built-in baseline");
  expect((await control("state")).runs).toBe(2);
  await auditAccessibility(page, testInfo, "hosted-regression-review");
  await page.reload(); await expect(page.getByRole("heading", { name: "Suite run · completed", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Past results for Paired computer suite", exact: true }).click();
  await expect(page.getByRole("link", { name: /^Review suite comparison / })).toBeVisible();
  await page.getByRole("navigation", { name: "Workspace" }).getByRole("link", { name: "Discovery", exact: true }).click();
  await page.getByLabel("Candidate duration (simulated seconds)").fill("1");
  await page.getByLabel("Maximum total executions").fill("3");
  await page.getByLabel("Maximum search candidates").fill("1");
  await page.getByLabel("Maximum candidates to confirm").fill("1");
  await page.getByLabel("Simulated-time budget (seconds)").fill("3");
  await page.getByRole("button", { name: "Build a plan for review" }).click();
  await expect(page.getByRole("heading", { name: "Review the experiment plan" })).toBeVisible();
  expect((await control("state")).runs).toBe(2);
  await expect(page.getByRole("button", { name: "Approve and start discovery" })).toBeDisabled();
  await page.getByLabel("I approve this plan and its execution and time budgets").check();
  await page.getByRole("button", { name: "Approve and start discovery" }).click();
  await expect(page.getByRole("heading", { name: "No failure confirmed", exact: true })).toBeVisible();
  await expect(page.getByRole("region", { name: "Discovery trial evidence" })).toContainText("Negative observation");
  expect((await control("state")).runs).toBe(3);
  await auditAccessibility(page, testInfo, "hosted-discovery-desktop");
  await page.screenshot({ path: testInfo.outputPath("hosted-discovery-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 900 });
  await auditAccessibility(page, testInfo, "hosted-discovery-mobile");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("hosted-discovery-mobile.png"), fullPage: true });
  await page.reload(); await expect(page.getByRole("heading", { name: "No failure confirmed", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Sign out", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Welcome back" })).toBeVisible();
  expect(errors).toEqual([]); expect(new Set(destinations)).toEqual(new Set(["https://localhost:8058"]));
});
